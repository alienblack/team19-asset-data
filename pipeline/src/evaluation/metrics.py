"""Hidden-cell reconstruction metrics.

Scores an imputed frame against the values that were deliberately hidden by a
holdout mask (see :mod:`overhead_conductors.evaluation.holdout`). Pre-existing
missing values are never scored because they have no truth. The scorer never
generates or modifies masks.

Numeric attributes: MAE, RMSE, median absolute error, normalised RMSE and
signed bias (mean of imputed minus true; positive means the method guesses
high). Categorical attributes: accuracy, balanced accuracy and macro-F1, plus
:func:`per_class_report` for recall/precision by class.
"""

from __future__ import annotations

import warnings
from typing import Sequence

import numpy as np
import pandas as pd
from sklearn.metrics import (
    accuracy_score,
    balanced_accuracy_score,
    f1_score,
    mean_absolute_error,
    mean_squared_error,
    median_absolute_error,
)


_METRIC_COLUMNS = [
    "variable",
    "variable_type",
    "n_masked",
    "mae",
    "rmse",
    "median_absolute_error",
    "nrmse",
    "signed_bias",
    "accuracy",
    "balanced_accuracy",
    "macro_f1",
    "n_classes_truth",
]


def prepare_evaluation_holdout(
    X_test: pd.DataFrame,
    columns: Sequence[str],
    rate: float = 0.10,
    seed: int = 319,
) -> tuple[pd.DataFrame, pd.DataFrame, pd.DataFrame]:
    """Backward-compatible alias for :func:`holdout.prepare_holdout`."""
    from .holdout import prepare_holdout

    return prepare_holdout(X_test, columns, rate=rate, seed=seed)


def _validate_evaluation_inputs(
    truth: pd.DataFrame,
    imputed: pd.DataFrame,
    mask: pd.DataFrame,
    columns: Sequence[str],
) -> None:
    """Prevent positional misalignment and scoring unknown/unimputed values."""
    if not isinstance(truth, pd.DataFrame):
        raise TypeError("truth must be a pandas DataFrame.")
    if not truth.index.is_unique or not truth.columns.is_unique:
        raise ValueError("truth must have unique row indices and column names.")

    for name, other in (("imputed", imputed), ("mask", mask)):
        if not isinstance(other, pd.DataFrame):
            raise TypeError(f"{name} must be a pandas DataFrame.")
        if not truth.index.equals(other.index):
            raise ValueError(f"{name} index must exactly match truth index.")
        if not truth.columns.equals(other.columns):
            raise ValueError(f"{name} columns must exactly match truth columns.")

    unknown_columns = sorted(set(columns) - set(truth.columns))
    if unknown_columns:
        raise ValueError(f"Evaluation columns not found in truth: {unknown_columns}.")

    for column in columns:
        if not pd.api.types.is_bool_dtype(mask[column]) or mask[column].isna().any():
            raise ValueError(f"mask['{column}'] must contain only boolean values.")
        selected = mask[column].to_numpy(dtype=bool)
        if not selected.any():
            continue
        if truth[column].iloc[selected].isna().any():
            raise ValueError(f"Missing ground truth for evaluated cells of '{column}'.")
        if imputed[column].iloc[selected].isna().any():
            raise ValueError(f"Unfilled evaluation cells remain in '{column}'.")


def evaluate_imputation(
    truth: pd.DataFrame,
    imputed: pd.DataFrame,
    mask: pd.DataFrame,
    numeric_columns: Sequence[str],
    categorical_columns: Sequence[str],
) -> pd.DataFrame:
    """Score only deliberately hidden *known* values, not original missingness.

    Metric definitions are unchanged from the original evaluation module.
    ``mask`` can be generated by ``prepare_evaluation_holdout`` or externally
    by the scenario engine. The scorer never generates or modifies masks.
    """
    _validate_evaluation_inputs(
        truth, imputed, mask, [*numeric_columns, *categorical_columns]
    )
    rows: list[dict[str, object]] = []

    for column in numeric_columns:
        positions = mask[column].to_numpy(dtype=bool)
        if not positions.any():
            continue

        y_true = truth.loc[positions, column].astype(float).to_numpy()
        y_pred = imputed.loc[positions, column].astype(float).to_numpy()

        rmse = float(np.sqrt(mean_squared_error(y_true, y_pred)))
        scale = float(np.std(y_true))

        rows.append(
            {
                "variable": column,
                "variable_type": "numeric",
                "n_masked": int(positions.sum()),
                "mae": float(mean_absolute_error(y_true, y_pred)),
                "rmse": rmse,
                "median_absolute_error": float(
                    median_absolute_error(y_true, y_pred)
                ),
                "nrmse": rmse / scale if scale > np.finfo(float).eps else np.nan,
                "signed_bias": float(np.mean(y_pred - y_true)),
                "accuracy": np.nan,
                "balanced_accuracy": np.nan,
                "macro_f1": np.nan,
                "n_classes_truth": np.nan,
            }
        )

    for column in categorical_columns:
        positions = mask[column].to_numpy(dtype=bool)
        if not positions.any():
            continue

        y_true = truth.loc[positions, column].astype(str).to_numpy()
        y_pred = imputed.loc[positions, column].astype(str).to_numpy()

        with warnings.catch_warnings():
            # Single-class holdouts and predicted classes absent from the
            # truth are reported through n_classes_truth; sklearn's warnings
            # about them would only repeat that.
            warnings.simplefilter("ignore", category=UserWarning)
            accuracy = float(accuracy_score(y_true, y_pred))
            balanced = float(balanced_accuracy_score(y_true, y_pred))
            macro_f1 = float(f1_score(y_true, y_pred, average="macro", zero_division=0))

        rows.append(
            {
                "variable": column,
                "variable_type": "categorical",
                "n_masked": int(positions.sum()),
                "mae": np.nan,
                "rmse": np.nan,
                "median_absolute_error": np.nan,
                "nrmse": np.nan,
                "signed_bias": np.nan,
                "accuracy": accuracy,
                "balanced_accuracy": balanced,
                "macro_f1": macro_f1,
                "n_classes_truth": int(len(np.unique(y_true))),
            }
        )

    return pd.DataFrame(rows, columns=_METRIC_COLUMNS)


def per_class_report(
    truth: pd.DataFrame,
    imputed: pd.DataFrame,
    mask: pd.DataFrame,
    column: str,
) -> pd.DataFrame:
    """Recall, precision and F1 per class on the hidden cells of one categorical column."""
    _validate_evaluation_inputs(truth, imputed, mask, [column])
    positions = mask[column].to_numpy(dtype=bool)
    columns = ["variable", "class", "support", "predicted", "recall", "precision", "f1"]
    if not positions.any():
        return pd.DataFrame(columns=columns)
    y_true = truth.loc[positions, column].astype(str).to_numpy()
    y_pred = imputed.loc[positions, column].astype(str).to_numpy()
    classes = sorted(set(y_true) | set(y_pred))
    rows = []
    for label in classes:
        tp = int(np.sum((y_true == label) & (y_pred == label)))
        support = int(np.sum(y_true == label))
        predicted = int(np.sum(y_pred == label))
        recall = tp / support if support else np.nan
        precision = tp / predicted if predicted else np.nan
        f1 = (2 * precision * recall / (precision + recall)) if (support and predicted and (precision + recall) > 0) else (0.0 if support else np.nan)
        rows.append(
            {
                "variable": column,
                "class": label,
                "support": support,
                "predicted": predicted,
                "recall": recall,
                "precision": precision,
                "f1": f1,
            }
        )
    return pd.DataFrame(rows, columns=columns)
